export const getSystemById = (id: string): SystemInfo | undefined => {
  return bodySystems.find((system) => system.id === id);
};

export const getOrganById = (organId: string): { organ: typeof bodySystems[0]['organs'][0]; system: SystemInfo } | undefined => {
  for (const system of bodySystems) {
    const organ = system.organs.find((o) => o.id === organId);
    if (organ) {
      return { organ, system };
    }
  }
  return undefined;
};
